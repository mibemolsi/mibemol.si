interface LanguageContextValue {
  language: Language
  setLanguage: (language: Language) => void
  t: (source: string) => string
}

const LanguageContext = createContext<LanguageContextValue>({ language: 'es', setLanguage: () => {}, t: (s) => s })

function readLanguage(): Language {
  try {
    const fromUrl = window.location.pathname.match(/^\/(en|es|pt)\/?$/)?.[1]
    if (fromUrl === 'en' || fromUrl === 'pt' || fromUrl === 'es') return fromUrl
    const value = localStorage.getItem(LANGUAGE_STORAGE_KEY)
    if (value === 'en' || value === 'pt' || value === 'es') return value
  } catch { /* storage may be unavailable */ }
  return 'es'
}

export function t(source: string): string {
  return activeLanguage === 'es' ? source : translations[activeLanguage][source] ?? source
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>(readLanguage)
  activeLanguage = language
  const setLanguage = (next: Language) => {
    activeLanguage = next
    setLanguageState(next)
    try { localStorage.setItem(LANGUAGE_STORAGE_KEY, next) } catch { /* storage may be unavailable */ }
    const url = new URL(window.location.href)
    url.pathname = `/${next}`
    window.history.replaceState(window.history.state, '', url)
  }
  useEffect(() => { document.documentElement.lang = language }, [language])
  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t,
  }), [language])
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useI18n() {
  return useContext(LanguageContext)
}
